// Scans src/pages/**/*.tsx for <InfoBubble title="..."> usages and regenerates
// src/data/infoBubbleIndex.ts so the search modal can find them.
// Run with: npm run generate:search-index (re-run after adding/removing InfoBubbles).
// Pass --check to fail instead of writing when the index is out of date.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pagesDir = path.join(__dirname, "..", "src", "pages");
const outFile = path.join(__dirname, "..", "src", "data", "infoBubbleIndex.ts");

const routeByFile = {
  "Home.tsx": "/",
  "Basics.tsx": "/fondamentaux",
  "Banking.tsx": "/systeme-bancaire",
  "PersonalFinance.tsx": "/finance-personnelle",
  "Investments.tsx": "/investissements",
  "Trading.tsx": "/trading",
  "Taxes.tsx": "/impots",
  "Resources.tsx": "/ressources",
  "Affiliation.tsx": "/affiliation",
  "Cryptos.tsx": "/cryptomonnaies",
  "CompoundInterest.tsx": "/interets-composes",
  "LoanCalculator.tsx": "/simulateur-pret",
  "Contact.tsx": "/contact",
  "Strategy.tsx": "/strategie",
  "Accounts.tsx": "/types-de-comptes",
  "ComparativeStudies.tsx": "/comparatifs-et-etudes",
  "InvestmentDecisionTree.tsx": "/organigramme-investissement",
  "RentVsBuy.tsx": "/louer-ou-acheter",
  "TaxWrapperComparator.tsx": "/comparateur-enveloppes",
  "BrokerComparator.tsx": "/comparateur-courtiers",
  "Tools.tsx": "/outils",
  "RiskProfile.tsx": "/profil-de-risque",
  "Legal.tsx": "/mentions-legales",
  "Licenses.tsx": "/licences",
};

function extractPageTitle(content) {
  const layoutIndex = content.indexOf("<PageLayout");
  if (layoutIndex === -1) return undefined;
  const match = content.slice(layoutIndex).match(/title="((?:[^"\\]|\\.)*)"/);
  return match?.[1];
}

function extractInfoBubbleTitles(content) {
  const lines = content.split("\n");
  const titles = [];
  for (let i = 0; i < lines.length; i++) {
    if (!lines[i].includes("<InfoBubble")) continue;
    for (let j = i; j < Math.min(i + 6, lines.length); j++) {
      const match = lines[j].match(/title="((?:[^"\\]|\\.)*)"/);
      if (match) {
        titles.push(match[1]);
        break;
      }
    }
  }
  return titles;
}

const pageFiles = readdirSync(pagesDir, { recursive: true })
  .map((relativePath) => ({
    relativePath,
    file: path.basename(relativePath),
    key: path.basename(relativePath).toLowerCase(),
  }))
  .sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));

const entries = [];
for (const { relativePath, file } of pageFiles) {
  const route = routeByFile[file];
  if (!route) continue;
  const content = readFileSync(path.join(pagesDir, relativePath), "utf8");
  const pageTitle = extractPageTitle(content);
  for (const title of extractInfoBubbleTitles(content)) {
    entries.push({ title, subtitle: pageTitle, to: route });
  }
}

const escape = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
const body = entries
  .map(
    (e) =>
      `  { title: "${escape(e.title)}", subtitle: "${escape(e.subtitle ?? "")}", to: "${e.to}" },`,
  )
  .join("\n");

const output = `// Generated by scripts/generate-infobubble-index.mjs — do not edit by hand.
import type { SearchEntry } from "./searchIndex";

export const infoBubbleIndex: SearchEntry[] = [
${body}
];
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8").replaceAll("\r\n", "\n");
  if (current !== output) {
    console.error(
      `${path.relative(process.cwd(), outFile)} is out of date. Run npm run generate:search-index.`,
    );
    process.exit(1);
  }
  console.log(`${entries.length} entries, index up to date.`);
  process.exit(0);
}

writeFileSync(outFile, output, "utf8");
console.log(
  `Wrote ${entries.length} entries to ${path.relative(process.cwd(), outFile)}`,
);
